import { afterEach, expect, it, vi } from 'vitest';
import { randomUUID } from 'node:crypto';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import sharp from 'sharp';
const { edit } = vi.hoisted(() => ({ edit: vi.fn() }));
vi.mock('../services/openAIClient.js', () => ({ createOpenAIClient: () => ({ images: { edit } }) }));
import { liveRatioRegenerator } from './protectedTemplates/product/ratioRegeneration.js';
import { createLayerEdits } from './layerEdit.js';
import { prepareLayerEdit } from './layerEditImage.js';
const dirs: string[] = [];
afterEach(() => { edit.mockReset(); vi.unstubAllEnvs(); dirs.splice(0).forEach(dir => rmSync(dir, { recursive: true, force: true })); });
it('sends one reference edit without preview-only parameters and converts the opaque output to an expanded transparent layer', async () => {
  vi.stubEnv('OPENAI_IMAGE_MODEL', 'gpt-image-2');
  const image = await sharp(Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="200" height="400"><rect x="30" y="20" width="140" height="360" fill="#9e6847"/></svg>')).png().toBuffer();
  const prepared = await prepareLayerEdit(image);
  const output = await sharp(Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024"><rect width="1024" height="1024" fill="${prepared.ground}"/><path d="M172 300 L392 232 H632 L852 300 V740 L632 792 H392 L172 740 Z" fill="#9e6847"/><rect x="410" y="270" width="204" height="490" fill="#334155"/></svg>`)).png().toBuffer();
  edit.mockResolvedValue({ data: [{ b64_json: output.toString('base64') }], _request_id: 'offline-request', usage: { input_tokens_details: { text_tokens: 1500, image_tokens: 6800 }, output_tokens: 7033 } });
  const provider = liveRatioRegenerator(), save = vi.fn(), operationId = randomUUID(), dir = mkdtempSync(join(tmpdir(), 'layer-edit-adapter-'));
  dirs.push(dir);
  const service = createLayerEdits({ dir, provider: () => provider, resolve: async () => ({ bytes: image, name: 'Brown refrigerator' }) });
  const result = await service.generate({ target: { kind: 'creative', templateId: 'pt-test', creativeId: 'pc-123abc', layerId: 'object-refrigerator', revision: 1 }, sourceSha256: prepared.sourceSha256, prompt: 'Open both doors', model: provider.model, approveUsd: 0.27, operationId });
  const [request, options] = edit.mock.calls[0];
  expect(request).toMatchObject({ model: 'gpt-image-2', quality: 'high', n: 1, size: '1024x1024', output_format: 'png' });
  expect(request).not.toHaveProperty('background');
  expect(request.prompt).toContain(`completely flat ${prepared.ground} background`);
  expect(Buffer.from(await request.image.arrayBuffer())).toEqual(prepared.image);
  expect(request.input_fidelity).toBeUndefined(); expect(request.mask).toBeUndefined();
  expect(options).toMatchObject({ maxRetries: 0, timeout: 300000, headers: { 'X-Client-Request-Id': operationId } });
  expect(result).toMatchObject({ requestId: 'offline-request', costUsd: 0.273, validation: { background: 'removed' } });
  expect(result.geometry.width).toBeGreaterThan(2);
  const { data } = await sharp(Buffer.from(result.image.base64, 'base64')).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  expect(data.some((value, index) => index % 4 === 3 && value === 0)).toBe(true);
  expect(edit).toHaveBeenCalledTimes(1);
  await provider.regenerate({ image, prompt: 'Existing resize request', size: { width: 1024, height: 1536 } }, save, 'offline-existing');
  expect(edit.mock.calls[1][0]).not.toHaveProperty('background');
});
it('does not resubmit when the image API fails or returns no image', async () => {
  const provider = liveRatioRegenerator(), input = { image: Buffer.from('fixture'), prompt: 'Edit', size: { width: 1024, height: 1024 }, background: 'transparent' as const };
  edit.mockRejectedValueOnce(new Error('Offline quota failure'));
  await expect(provider.regenerate(input, () => {}, 'offline-failed')).rejects.toThrow('quota');
  expect(edit).toHaveBeenCalledTimes(1);
  edit.mockResolvedValueOnce({ data: [] });
  await expect(provider.regenerate(input, () => {}, 'offline-empty')).rejects.toThrow('no image');
  expect(edit).toHaveBeenCalledTimes(2);
});
it('sends the layer first and the original product second, with the area mask applying to the layer, at a fitted size', async () => {
  vi.stubEnv('OPENAI_IMAGE_MODEL', 'gpt-image-2');
  const svg = (w: number, h: number, body: string) => sharp(Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}">${body}</svg>`)).png().toBuffer();
  const layer = await svg(200, 400, '<rect x="30" y="20" width="140" height="360" fill="#9e6847"/>'), original = await svg(200, 400, '<rect x="30" y="20" width="140" height="360" fill="#7b4f35"/>');
  const p = await prepareLayerEdit(layer, { intent: { operations: ['remove'], preserveIdentity: true, expandsSilhouette: false }, region: { x: 0.4, y: 0.4, width: 0.3, height: 0.2 }, identity: original });
  edit.mockResolvedValue({ data: [{ b64_json: p.image.toString('base64') }], _request_id: 'offline-request' });
  const save = vi.fn();
  await liveRatioRegenerator().regenerate({ image: p.image, references: p.references, mask: p.mask, size: p.size, prompt: 'Remove the sticker' }, save, 'offline-masked');
  const [request] = edit.mock.calls[0];
  expect(request.size).toBe(`${p.size.width}x${p.size.height}`); expect(p.size.width).not.toBe(p.size.height);
  expect(request.image).toHaveLength(2);
  expect(Buffer.from(await request.image[0].arrayBuffer())).toEqual(p.image); expect(Buffer.from(await request.image[1].arrayBuffer())).toEqual(p.references[0]);
  expect(Buffer.from(await request.mask.arrayBuffer())).toEqual(p.mask);
  expect(request.input_fidelity).toBeUndefined(); expect(request).not.toHaveProperty('background');
  expect(save.mock.calls[0][1]).toMatchObject({ image: ['<the creative, as sent>', '<reference 2, as sent>'], mask: '<the edit mask, as sent>' });
  expect(edit).toHaveBeenCalledTimes(1);
});
