import { test, expect } from '@playwright/test';
import { mkdirSync, writeFileSync } from 'node:fs';
import sharp from 'sharp';
import type { ProjectDocument, ReuseDraft } from '@frameflow/shared';
import type { ProductView } from '../../client/src/features/productTemplates/api';

// Run only on a copied replay, never against the user's stored master or live providers.
const id = process.env.FRAMEFLOW_GANESH_REPLAY_ID;
const API = '/api/layerize-experiment/product-templates';
const OUT = 'test-results/ganesh-browser';
test.use({ extraHTTPHeaders: { origin: `http://127.0.0.1:${process.env.FRAMEFLOW_OFFLINE_E2E_PORT ?? 3317}` }, actionTimeout: 30000 });
test.setTimeout(600000);

test('repaired recorded master: editable layers, saved master, replacement in 16:9, save and editor', async ({ page, request }) => {
  test.skip(!id || !process.env.FRAMEFLOW_SAVED_VARIATION_FIXTURE, 'Requires an isolated Ganesh replay copy.');
  mkdirSync(OUT, { recursive: true });
  await page.route(url => /^https?:$/.test(url.protocol) && url.hostname !== '127.0.0.1', r => r.abort());
  let v = await (await request.get(`${API}/${id}`)).json() as ProductView;
  expect(v.product.prepared!.quality.issues.filter(i => i.blocking)).toEqual([]);
  const approved = await request.post(`${API}/${id}/approve`, { data: { expectedRevision: v.template.revision, acknowledge: v.product.prepared!.quality.issues.map(i => i.id) } });
  expect(approved.ok(), await approved.text()).toBe(true);
  v = await approved.json();
  const published = await request.post(`${API}/${id}/publish`, { data: { expectedRevision: v.template.revision } });
  expect(published.ok(), await published.text()).toBe(true);

  await page.goto('/');
  await page.getByRole('button', { name: 'OpenAI + Seedream test' }).click();
  const panel = page.getByRole('dialog', { name: 'OpenAI + Seedream test' });
  await panel.getByRole('tab', { name: 'Offer Templates', exact: true }).click();
  await panel.getByRole('article').filter({ has: page.locator(`img[src*="${id}"]`) }).first().getByRole('button', { name: 'Edit master', exact: true }).click();
  await panel.getByRole('button', { name: 'Open in Editor', exact: true }).click();
  await expect(panel).toBeHidden({ timeout: 60000 });
  const stored = () => page.evaluate(() => JSON.parse(localStorage.getItem('frameflow:project:v1')!) as ProjectDocument);
  await expect.poll(async () => (await stored()).variants.some(x => x.importedFrom?.runId), { timeout: 60000 }).toBe(true);
  const design = (await stored()).variants.find(x => x.importedFrom?.runId)!;
  expect(design.elements.filter(e => e.text).length).toBeGreaterThanOrEqual(42);
  await page.screenshot({ path: `${OUT}/01-master-editor.png` });
  const product = design.layers!.find(l => /refrigerator/i.test(l.name) && !/^Stand/i.test(l.name))!;
  expect(product).toBeTruthy();
  await page.locator(`[data-layer-id="${product.id}"] .layer-select`).click();
  await page.getByLabel('X', { exact: true }).fill(String(Math.round(product.x) - 40));
  await page.getByLabel('X', { exact: true }).blur();
  await expect.poll(async () => (await stored()).variants.find(x => x.id === design.id)!.layers!.find(l => l.id === product.id)!.x).toBe(Math.round(product.x) - 40);
  await page.locator(`[data-layer-id="${product.id}"]`).getByRole('button', { name: `Hide ${product.name}`, exact: true }).click();
  await expect.poll(async () => (await stored()).variants.find(x => x.id === design.id)!.layers!.find(l => l.id === product.id)!.visible).toBe(false);
  await page.screenshot({ path: `${OUT}/01b-product-hidden.png` });
  await page.locator(`[data-layer-id="${product.id}"]`).getByRole('button', { name: `Show ${product.name}`, exact: true }).click();
  const logo = design.layers!.find(l => l.name === 'LG logo')!;
  await page.locator(`[data-layer-id="${logo.id}"] .layer-select`).click();
  await page.getByLabel('X', { exact: true }).fill(String(Math.round(logo.x) + 30));
  await page.getByLabel('X', { exact: true }).blur();
  await expect.poll(async () => (await stored()).variants.find(x => x.id === design.id)!.layers!.find(l => l.id === logo.id)!.x).toBe(Math.round(logo.x) + 30);
  await page.getByRole('tab', { name: 'Text', exact: true }).click();
  await page.locator('.text-elements summary').filter({ hasText: 'GANESH' }).first().click();
  await page.getByRole('button', { name: 'Select word GANESH', exact: true }).click();
  await page.getByLabel('Text content', { exact: true }).fill('FESTIVE');
  await page.getByLabel('Text content', { exact: true }).blur();
  await page.getByRole('button', { name: 'Save creative', exact: true }).click();
  await expect(page.getByText(/Saved to creative · revision \d+/)).toBeVisible();
  await page.reload();
  expect((await stored()).variants.find(x => x.id === design.id)!.elements.some(e => e.text === 'FESTIVE')).toBe(true);
  await page.screenshot({ path: `${OUT}/02-master-edited-reloaded.png` });
  const exportFile = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export PNG', exact: true }).click();
  await (await exportFile).saveAs(`${OUT}/03-master-export.png`);

  await page.getByRole('button', { name: 'Create Offer Creative', exact: true }).click();
  const app = page.getByRole('dialog', { name: 'Create Offer Creative' });
  await app.getByRole('article').filter({ has: page.locator(`img[src*="${id}"]`) }).first().getByRole('button', { name: 'Use This Template' }).click();
  await app.getByRole('radiogroup', { name: 'Creative size' }).getByRole('radio', { name: /Landscape 16:9/ }).click();
  const packshot = await sharp(Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="420" height="540"><rect x="10" y="10" width="400" height="520" rx="22" fill="#f3f4f6" stroke="#9ca3af" stroke-width="6"/><circle cx="210" cy="300" r="120" fill="#60a5fa"/></svg>')).png().toBuffer();
  await app.getByLabel('Upload product photos').setInputFiles({ name: 'washing-machine.png', mimeType: 'image/png', buffer: packshot });
  await expect(app.getByRole('list', { name: 'Your products' }).getByRole('listitem', { name: /^Product / })).toHaveCount(1, { timeout: 60000 });
  await app.getByRole('button', { name: 'Generate Creative', exact: true }).click();
  await page.getByRole('dialog', { name: /Design Your Creative with AI/ }).getByRole('button', { name: 'Generate Automatically (Free)' }).click();
  await expect(app.getByRole('heading', { name: 'Your creative is ready!' })).toBeVisible({ timeout: 120000 });
  await page.screenshot({ path: `${OUT}/04-reuse-16x9.png` });
  await app.getByRole('button', { name: 'Save Creative', exact: true }).click();
  await expect(app.getByRole('button', { name: 'Saved', exact: true })).toBeVisible();
  const drafts = (await (await request.get(`${API}/${id}/reuse`)).json()).drafts as ReuseDraft[];
  const d = drafts.find(x => x.simple && x.ratios.includes('16:9'))!;
  const detail = (await (await request.get(`${API}/${id}/reuse/${d.id}`)).json()).draft as ReuseDraft;
  expect(detail.outputs['16:9']!.creativeId).toBeTruthy();
  const preview = await (await request.get(`${API}/${id}/reuse/${d.id}/preview?ratio=16x9`)).json();
  expect(preview.checks.issues.filter((i: { blocking: boolean }) => i.blocking)).toEqual([]);
  // Common-ratio composition can preserve the extracted stands; stageCleaned specifically
  // describes the optional empty-stage path, not whether the master passed residue checks.
  expect((await (await request.get(`${API}/${id}/reuse/${d.id}`)).json()).sourceIssues).toEqual([]);
  expect(preview.creative.canvas.width * 9).toBe(preview.creative.canvas.height * 16);
  const products = preview.creative.objects.filter((o: { kind: string; hidden: boolean }) => o.kind === 'product' && !o.hidden);
  expect(products).toHaveLength(1);
  // One product leaves most of the display empty: arranged anew on the podium as the hero, the template's stands left
  // out (the rejected 16:9 creative showed it in one small place among thirteen abandoned risers).
  expect(preview.creative.objects.filter((o: { kind: string; hidden: boolean }) => o.kind === 'podium' && !o.hidden)).toEqual([]);
  expect(products[0].box.height).toBeGreaterThan(preview.creative.canvas.height * 0.2);
  const upload = detail.items.find(i => !i.objectId && i.kind === 'product')!;
  if (upload.asset.kind !== 'upload') throw new Error('The replacement must retain its uploaded asset.');
  expect(products[0].asset.sha256).toBe(upload.asset.sha256);
  expect(preview.creative.texts.filter((t: { hidden: boolean }) => !t.hidden)).toHaveLength(42);
  expect(preview.creative.images.filter((i: { hidden: boolean }) => !i.hidden)).toHaveLength(19);
  writeFileSync(`${OUT}/checks.json`, JSON.stringify({ templateId: id, draft: detail, checks: preview.checks }, null, 2));
  await app.getByRole('button', { name: 'Decompose into Layers', exact: true }).click();
  await page.getByRole('dialog', { name: 'Make Your Creative Editable' }).getByRole('button', { name: /^Make Editable/ }).click({ timeout: 120000 });
  await page.getByRole('dialog', { name: 'Your Creative Is Ready to Edit!' }).getByRole('button', { name: 'Open Visual Editor' }).click({ timeout: 180000 });
  await expect(app).toBeHidden({ timeout: 60000 });
  const reused = (await stored()).variants.filter(x => x.id !== design.id && x.productTemplate).at(-1)!;
  expect(reused.canvas.width * 9).toBe(reused.canvas.height * 16);
  expect(reused.elements.filter(e => e.type === 'text')).toHaveLength(42);
  await page.getByRole('tab', { name: 'Text', exact: true }).click();
  await page.locator('.text-elements summary').filter({ hasText: 'GANESH' }).first().click();
  await page.getByRole('button', { name: 'Select word GANESH', exact: true }).click();
  await page.getByLabel('Text content', { exact: true }).fill('FESTIVE');
  await page.getByLabel('Text content', { exact: true }).blur();
  await page.getByRole('button', { name: 'Save creative', exact: true }).click();
  await expect(page.getByText(/Saved to creative · revision \d+/)).toBeVisible();
  await page.reload();
  const reopened = (await stored()).variants.find(x => x.id === reused.id)!;
  expect(reopened.canvas).toEqual(reused.canvas);
  expect(reopened.elements.some(e => e.text === 'FESTIVE')).toBe(true);
  await page.screenshot({ path: `${OUT}/05-reuse-editor.png` });
  const reuseExport = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export PNG', exact: true }).click();
  await (await reuseExport).saveAs(`${OUT}/06-reuse-export.png`);
  const exportedSize = await sharp(`${OUT}/06-reuse-export.png`).metadata();
  expect(exportedSize.width! * 9).toBe(exportedSize.height! * 16);
});
