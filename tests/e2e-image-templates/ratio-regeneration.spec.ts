import { test, expect, type APIRequestContext, type Page } from '@playwright/test';
import { mkdirSync } from 'node:fs';
import sharp from 'sharp';
import type { ProjectDocument, ReuseDraft } from '@frameflow/shared';
import type { ProductView } from '../../client/src/features/productTemplates/api';

// A creative regenerated in the chosen size by the image model, in both workflows (offline: the image model is a test
// double that places the creative whole on a soft cover of itself — nothing is generated, nothing paid, nothing leaves the
// machine). First-time master: Upload (16:9, regenerate approved) → look at it, approve → the regenerated creative is found,
// reviewed, decomposed, saved and opened in the editor at 16:9. Create Offer Creative: size 9:16 → a product → regenerate
// (cost confirmed) → look at it, approve → made editable through the same pipeline.
const API = '/api/layerize-experiment/product-templates', OUT = 'test-results/ratio-regeneration';
test.use({ extraHTTPHeaders: { origin: `http://127.0.0.1:${process.env.FRAMEFLOW_OFFLINE_E2E_PORT ?? 3317}` }, actionTimeout: 30000 });
test.setTimeout(300000);
const exact = (c: { width: number; height: number }, w: number, h: number) => c.width * h === c.height * w;

async function lab(page: Page) {
  await page.goto('/');
  await page.getByRole('button', { name: 'OpenAI + Seedream test' }).click();
  const panel = page.getByRole('dialog', { name: 'OpenAI + Seedream test' });
  await panel.getByRole('tab', { name: 'Offer Templates', exact: true }).click();
  return panel;
}

test('first-time master: regenerated in 16:9 at upload, approved, then found, reviewed, decomposed, saved and edited at 16:9', async ({ page, request }, info) => {
  test.skip(info.project.name !== 'desktop', 'One run of this long flow.');
  mkdirSync(OUT, { recursive: true });
  await page.route(url => /^https?:$/.test(url.protocol) && url.hostname !== '127.0.0.1', r => r.abort());
  const panel = await lab(page), name = `Regenerated master ${Date.now().toString(36)}`;
  await panel.getByRole('button', { name: 'New product template' }).click();
  await panel.getByLabel('Creative to upload').setInputFiles({ name: 'poster.png', mimeType: 'image/png', buffer: await (await request.get('/__test__/product-poster.png')).body() });
  await panel.getByLabel('Template name').fill(name);
  await panel.getByRole('group', { name: 'Size of the master template' }).getByRole('radio', { name: /Landscape 16:9/ }).click();
  // The regeneration is offered for a common ratio, with its estimate; ticking it approves that cost.
  const option = panel.getByTestId('regenerate-option');
  await expect(option).toContainText('Regenerate the creative in Landscape 16:9 with AI first'); await expect(option).toContainText('at most about $');
  await option.getByRole('checkbox').check();
  await panel.getByRole('checkbox', { name: /Find characters and products with AI/ }).check();
  await page.screenshot({ path: `${OUT}/01-upload-regenerate-16x9.png` });
  const created = page.waitForResponse(r => r.url().endsWith(API) && r.request().method() === 'POST');
  await panel.getByRole('button', { name: 'Upload and regenerate in Landscape 16:9' }).click();
  const id = ((await (await created).json()) as ProductView).template.id;
  // Looked at before anything else runs: the original beside it, what was checked; nothing until confirmed.
  await expect(panel.getByRole('heading', { name: 'Your creative regenerated in Landscape 16:9' })).toBeVisible({ timeout: 120000 });
  const result = panel.getByRole('region', { name: 'Regenerated in Landscape 16:9' });
  await expect(result.getByRole('img', { name: /Your creative regenerated by AI in Landscape 16:9/ })).toBeVisible();
  await expect(result.getByRole('list', { name: 'Checked before you use it' })).toContainText('exactly 16:9');
  const use = panel.getByRole('button', { name: 'Use this design and continue' });
  await expect(use).toBeDisabled();
  await page.screenshot({ path: `${OUT}/02-regenerated-review.png` });
  await result.getByRole('checkbox', { name: /I have looked at the regenerated creative/ }).check();
  await use.click();
  // The regenerated creative is what the pipeline processes.
  await expect(panel.getByRole('heading', { name: 'Here’s what we found' })).toBeVisible({ timeout: 120000 });
  await expect(panel.getByTestId('chosen-size')).toContainText('regenerated by AI and approved by you');
  const v = (await (await request.get(`${API}/${id}`)).json()) as ProductView;
  expect(v.template.source).toMatchObject({ width: 2048, height: 1152 }); expect(v.product.regeneration?.status).toBe('approved');
  await panel.getByRole('button', { name: 'Save and choose what to decompose' }).click();
  await panel.getByRole('button', { name: 'Continue to Decomposition' }).click();
  await expect(panel.getByRole('heading', { name: 'Inspect the layers and the background' })).toBeVisible({ timeout: 120000 });
  for (const c of await panel.getByRole('complementary', { name: 'Checks' }).getByRole('checkbox').all()) await c.check();
  // Already its size: saved as it is (no further adaptation).
  await expect(panel.getByRole('group', { name: 'Size of the master template' }).getByRole('radio', { name: /^Original/ })).toHaveAttribute('aria-checked', 'true');
  const draft = panel.getByRole('button', { name: 'Save as a draft with these warnings…' });
  if (await draft.isVisible()) { await draft.click(); await panel.getByRole('button', { name: 'Yes, save as a draft' }).click(); }
  else await panel.getByRole('button', { name: 'Save master template' }).click();
  await expect(panel.getByRole('heading', { name: 'Your template is saved' })).toBeVisible({ timeout: 60000 });
  await page.screenshot({ path: `${OUT}/03-master-saved.png` });
  // The editor opens it at exactly 16:9.
  const opened = page.waitForResponse(r => r.url().endsWith(`/${id}/open-editor`) && r.request().method() === 'POST');
  await panel.getByRole('button', { name: 'Open in Editor', exact: true }).click();
  const { runId } = await (await opened).json();
  await expect(panel).toBeHidden({ timeout: 60000 });
  const stored = () => page.evaluate(() => JSON.parse(localStorage.getItem('frameflow:project:v1')!) as ProjectDocument);
  await expect.poll(async () => (await stored()).variants.some(x => x.importedFrom?.runId === runId), { timeout: 60000 }).toBe(true);
  const design = (await stored()).variants.find(x => x.importedFrom?.runId === runId)!;
  expect(design.canvas).toMatchObject({ width: 2048, height: 1152 }); expect(design.layers!.length).toBeGreaterThan(2);
  await page.screenshot({ path: `${OUT}/04-editor-16x9.png` });
});

async function savedTemplate(request: APIRequestContext, name: string) {
  const poster = await (await request.get('/__test__/product-poster.png')).body();
  let v = await (await request.post(API, { multipart: { name, useAi: 'true', image: { name: 'poster.png', mimeType: 'image/png', buffer: poster } } })).json() as ProductView;
  const id = v.template.id;
  await expect.poll(async () => { v = await (await request.get(`${API}/${id}`)).json(); return v.stage; }, { timeout: 60000 }).toBe('review');
  v = await (await request.put(`${API}/${id}/review`, { data: { expectedRevision: v.template.revision, objects: v.product.objects.map(o => ({ id: o.id, kind: o.kind, label: o.label, box: o.box, accepted: true })), texts: [], logos: [] } })).json();
  await request.post(`${API}/${id}/prepare`, { data: { expectedRevision: v.template.revision } });
  await expect.poll(async () => { v = await (await request.get(`${API}/${id}`)).json(); return v.stage; }, { timeout: 120000 }).toBe('prepared');
  v = await (await request.post(`${API}/${id}/approve`, { data: { expectedRevision: v.template.revision, acknowledge: v.product.prepared!.quality.issues.map(i => i.id) } })).json();
  v = await (await request.post(`${API}/${id}/publish`, { data: { expectedRevision: v.template.revision } })).json();
  return id;
}

test('Create Offer Creative: size 9:16 at the start, a product, regenerated with AI (cost confirmed), approved, made editable', async ({ page, request }, info) => {
  test.skip(info.project.name !== 'desktop', 'One run of this long flow.');
  mkdirSync(OUT, { recursive: true });
  await page.route(url => /^https?:$/.test(url.protocol) && url.hostname !== '127.0.0.1', r => r.abort());
  const name = `Regenerated offer ${Date.now().toString(36)}`, id = await savedTemplate(request, name);
  await page.goto('/');
  await page.getByRole('button', { name: 'Create Offer Creative' }).click();
  const app = page.getByRole('dialog', { name: 'Create Offer Creative' });
  await app.getByRole('region', { name: 'Choose your size' }).getByRole('radio', { name: /Story 9:16/ }).click();
  await app.getByRole('article', { name: `Template ${name}` }).getByRole('button', { name: 'Use This Template' }).click();
  const packshot = await sharp(Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="360" height="520"><rect x="10" y="10" width="340" height="500" rx="24" fill="#c9ced6"/><rect x="50" y="50" width="260" height="150" rx="10" fill="#20252c"/><circle cx="180" cy="340" r="90" fill="#5b7fb6"/></svg>')).png().toBuffer();
  await app.getByLabel('Upload product photos').setInputFiles({ name: 'washing-machine.png', mimeType: 'image/png', buffer: packshot });
  await expect(app.getByRole('list', { name: 'Your products' }).getByRole('listitem', { name: /Product washing machine/ })).toBeVisible({ timeout: 60000 });
  await app.getByRole('button', { name: 'Generate Creative' }).click();
  const ask = page.getByRole('dialog', { name: /Design Your Creative with AI|Arrange Products with AI/ });
  if (await ask.isVisible().catch(() => false)) await ask.getByRole('button', { name: 'Generate Automatically (Free)' }).click();
  // The AI regeneration of this size, offered on the result; nothing is sent before its cost is confirmed.
  const panel = app.getByRole('region', { name: 'Regenerate with AI' });
  await expect(panel).toBeVisible({ timeout: 120000 });
  await panel.getByRole('button', { name: 'Regenerate with AI…' }).click();
  await expect(panel.getByRole('group', { name: 'Confirm the AI regeneration cost' })).toContainText('at most about $');
  await page.screenshot({ path: `${OUT}/05-offer-confirm-cost.png` });
  await panel.getByRole('button', { name: 'Yes, regenerate with AI' }).click();
  const result = panel.getByRole('region', { name: 'Regenerated in Story 9:16' });
  await expect(result.getByRole('list', { name: 'Checked before you use it' })).toContainText('exactly 9:16', { timeout: 120000 });
  await expect(result.getByRole('list', { name: 'Checked before you use it' })).toContainText('washing machine: your own picture put back');
  const use = panel.getByRole('button', { name: /Use it: make it editable/ });
  await expect(use).toBeDisabled();
  await page.screenshot({ path: `${OUT}/06-offer-regenerated-9x16.png` });
  await result.getByRole('checkbox', { name: /I have looked at the regenerated creative/ }).check();
  await use.click();
  // Made editable through the creation pipeline: its own template, its elements found in the regenerated picture.
  await expect(app.getByRole('heading', { name: 'Here’s what we found' })).toBeVisible({ timeout: 120000 });
  await page.screenshot({ path: `${OUT}/07-offer-editable-review.png` });
  const drafts = (await (await request.get(`${API}/${id}/reuse`)).json()).drafts as { id: string; simple: boolean }[];
  const d = (await (await request.get(`${API}/${id}/reuse/${drafts.find(x => x.simple)!.id}`)).json()).draft as ReuseDraft;
  const made = (await (await request.get(`${API}/${d.regenImages!['9:16']!.templateId}`)).json()) as ProductView;
  expect(exact(made.template.source, 9, 16)).toBe(true); expect(made.product.regeneration).toMatchObject({ status: 'approved', ratio: '9:16', from: { templateId: id } });
});
